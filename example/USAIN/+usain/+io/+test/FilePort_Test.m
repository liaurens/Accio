        function save_file__overwrite_existing_files(Obj)
            % GIVEN a nonexisting file
            p = pathlib.Path(mfilename('fullpath')).parent / '_generated' / 'fileport-test01.usn';
            if p.is_file()
                delete(char(p));
            end

            % WHEN, THEN
            F = usain.io.FilePort();
            F.save_file(p);
            Obj.assertTrue(p.is_file());

            % WHEN saving the same file again, THEN
            Obj.assertError(@() F.save_file(p), 'FilePort:ExistingPath');

            % WHEN saving the same file again, but with the 'force' arg, THEN
            Obj.verify_error_free(@() F.save_file(p, true));
        end

