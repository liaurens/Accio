        function get_object_to_save__converted_to_basic_types(Obj)
            % GIVEN
            F = usain.io.FilePort();

            % WHEN filling the FilePort with dummy data
            O = gobjects();
            O.addprop('a');
            O.a = 'a';
            F.data.a = O;  % to test if objects are converted to structs
            F.data.b.c = 123;

            % THEN
            Actual = F.get_object_to_save();

            Obj.assertClass(Actual, 'struct');
            Obj.assertTrue(isfield(Actual, 'FILE_VERSION'));
            Obj.assertTrue(isfield(Actual, 'toolName'));
            Obj.assertTrue(isfield(Actual, 'toolVersion'));
            Obj.assertTrue(isfield(Actual, 'data'));
            Obj.assertTrue(isfield(Actual, 'TYPES'));
            Obj.assertTrue(isstruct(Actual.data.a));  % converted to struct
            Obj.assertEqual(Actual.data.b.c, 123);
        end

        function get_data__expected_fields(Obj)
            % GIVEN a fake USAIN instance with some pre-defined data
            UsainObj = Obj.create_fake_usain_object();

            % WHEN we construct the FilePort
            actual = usain.io.FilePort.get_data(UsainObj);

            % THEN
            Obj.assertClass(actual, 'struct');
            Obj.assertEqual(actual.washer.diameterIn, 100);
            Obj.assertEqual(actual.washer.diameterOut, 200);
            Obj.assertEqual(actual.washer.thickness, 123);
            Obj.assertEqual(actual.boltForceModel.plotData.line.x, [1, 1, 1, 1]');
            Obj.assertEqual(actual.boltForceModel.plotData.marker.y, [3, 4]);

            % WHEN we do the same, but then through the constructor of usain.io.FilePort
            F = usain.io.FilePort(UsainObj);

            % THEN we expect a FilePort object to be returned, with the exact same data as before
            Obj.assertClass(F, 'usain.io.FilePort');
            Obj.assertEqual(F.data.washer.diameterIn, 100);
            Obj.assertEqual(F.data.washer.diameterOut, 200);
            Obj.assertEqual(F.data.washer.thickness, 123);
            Obj.assertEqual(F.data.boltForceModel.plotData.line.x, [1, 1, 1, 1]');
            Obj.assertEqual(F.data.boltForceModel.plotData.marker.y, [3, 4]);
        end

