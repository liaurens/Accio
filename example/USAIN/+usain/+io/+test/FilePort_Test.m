        function hash__expected(Obj)
            % GIVEN not run as compiled code and the SHA1 hash
            Obj.assumeFalse(isdeployed(), 'Skip this test when run as compiled code');
            actualClassName = 'usain.io.FilePort';
            actual = io.hash_file(which(actualClassName));

            % WHEN, THEN
            expected = 'fcd344d858d9f4de3eec96b1daab6883ad070b12';
            Obj.verifyEqual(actual, expected, ...
                sprintf(['Hash of %s class file changed!\n', ...
                'This hints at the class code being changed.\n', ...
                'If the change is not relevant for Python, update the expected checksum.\n', ...
                'Otherwise, follow the guide in "guides/fileport-matlab.md".'], ...
                actualClassName));
        end

